// Box test chain only: 24 h address + IP faucet cooldown with persistence. Uses a fresh TEST role key (never the real
// faucet key). argv[2] = faucet server.mjs path.
import { spawn } from 'node:child_process';
import { mkdtempSync, readFileSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Wallet, parseEther, formatEther } from 'ethers';
import { provider, roleWallet, queuedRole, GAS_PRICE } from '../lib/common.mjs';
const server = process.argv[2]; const PORT = 18789;
if (await fetch(`http://127.0.0.1:${PORT}/health`).then(() => true, () => false)) throw new Error(`port ${PORT} busy`);
const fw = roleWallet(`faucet24-${process.argv[3] || Date.now()}`);
if ((await provider.getBalance(fw.address)) < parseEther('60')) await (await (await queuedRole('deployer')).sendTransaction({ to: fw.address, value: parseEther('64'), gasPrice: GAS_PRICE })).wait();
const stateFile = join(mkdtempSync(join(tmpdir(), 'faucet24-')), 'state', 'claims.json');
let child;
async function start() {
  child = spawn(process.execPath, [server], { stdio: ['ignore', 'pipe', 'pipe'], env: { PATH: process.env.PATH, PORT: String(PORT), LISTEN_HOST: '127.0.0.1', RPC_URL: 'http://127.0.0.1:8545', FAUCET_PRIVATE_KEY: fw.privateKey, FAUCET_ADDRESS: fw.address, FAUCET_DRIP_ZNYT: '10', FAUCET_COOLDOWN_MS: '86400000', FAUCET_IP_COOLDOWN_MS: '86400000', FAUCET_STATE_FILE: stateFile, CHAIN_ID: '9127' } });
  let log = ''; child.stdout.on('data', (d) => (log += d)); child.stderr.on('data', (d) => (log += d));
  for (let i = 0; i < 80 && !/listening/.test(log); i++) await new Promise((r) => setTimeout(r, 100));
  return log;
}
process.on('exit', () => { try { child.kill(); } catch {} });
const claim = (address, ip) => fetch(`http://127.0.0.1:${PORT}/claim`, { method: 'POST', headers: { 'content-type': 'application/json', ...(ip ? { 'x-zeronyth-client-ip': ip } : {}) }, body: JSON.stringify({ address }) }).then(async (r) => ({ s: r.status, j: await r.json() }));
const R = {}; const ok = {};
const log1 = await start();
const health = await fetch(`http://127.0.0.1:${PORT}/health`).then((r) => r.json());
R.health = { dripZNYT: health.dripZNYT, cooldownHours: health.cooldownHours, ipCooldownSeconds: health.ipCooldownSeconds };
const A = Wallet.createRandom().address, B = Wallet.createRandom().address, C = Wallet.createRandom().address, D = Wallet.createRandom().address;
const a1 = await claim(A, '203.0.113.7');
const rc = a1.j.txHash ? await provider.waitForTransaction(a1.j.txHash, 1, 30_000) : null;
R.first = { status: a1.s, amount: a1.j.amountZNYT, receipt: rc?.status, balanceA: formatEther(await provider.getBalance(A)), nextClaimAtJst: a1.j.nextClaimAtJst };
const a2 = await claim(A, '198.51.100.9');
R.sameAddrOtherIp = { status: a2.s, code: a2.j.code, error: a2.j.error };
const b1 = await claim(B, '203.0.113.7');
R.sameIpNewAddr = { status: b1.s, code: b1.j.code, error: b1.j.error, retryAfterSeconds: b1.j.retryAfterSeconds };
const c1 = await claim(C, '198.51.100.20');
R.otherIpNewAddr = { status: c1.s };
const par = await Promise.all([Wallet.createRandom().address, Wallet.createRandom().address, Wallet.createRandom().address].map((x) => claim(x, '192.0.2.44')));
R.parallelSameIp = par.map((p) => p.s).sort().join(',');
const v6a = await claim(Wallet.createRandom().address, '2001:db8:4307:26be::3dc:18'); const v6b = await claim(Wallet.createRandom().address, '2001:db8:4307:26be:aaaa::1');
R.ipv6Same64 = `${v6a.s},${v6b.s}:${v6b.j.code}`;
const raw = readFileSync(stateFile, 'utf8');
R.state = { mode: (statSync(stateFile).mode & 0o777).toString(8), rawIpStored: /203\.0\.113\.7|198\.51\.100|192\.0\.2\.44/.test(raw) };
child.kill(); await new Promise((r) => setTimeout(r, 500));
const log2 = await start();
const a3 = await claim(A, '198.51.100.99'); const d1 = await claim(D, '203.0.113.7');
R.afterRestart = { addr: `${a3.s}:${a3.j.code}`, ip: `${d1.s}:${d1.j.code}`, log: log2.trim().split('\n').pop() };
for (const h of [c1, v6a, ...par].map((x) => x.j.txHash).filter(Boolean)) await provider.waitForTransaction(h, 1, 30_000);
ok.pass = R.health.dripZNYT === '10' && R.health.cooldownHours === 24 && a1.s === 200 && rc?.status === 1 && R.first.balanceA === '10.0' && a2.s === 429 && a2.j.code === 'cooldown_address' && b1.s === 429 && b1.j.code === 'cooldown_ip' && c1.s === 200 && R.parallelSameIp === '200,429,429' && R.state.mode === '600' && !R.state.rawIpStored && a3.s === 429 && d1.s === 429 && /日本時間/.test(b1.j.error) && R.ipv6Same64 === '200,429:cooldown_ip';
console.log(JSON.stringify({ ...R, ...ok }, null, 1));
child.kill(); process.exit(ok.pass ? 0 : 1);
