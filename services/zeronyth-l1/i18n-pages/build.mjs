// Builds dashboard/assets/i18n-pages-<locale>.mjs from the *.txt translation sources in this folder.
// Usage: node build.mjs [pool.json]   (pool = optional list of rendered strings, for "⋯" prefixes and a coverage report)
import fs from 'node:fs';
import path from 'node:path';
const DIR = path.dirname(new URL(import.meta.url).pathname);
const OUT = path.join(DIR, '..', 'dashboard', 'assets');
const LOCS = ['ja', 'en', 'zh-CN', 'ko'];
const norm = (s) => s.replace(/\s+/g, ' ').trim();
const poolFile = process.argv[2];
const pool = poolFile ? JSON.parse(fs.readFileSync(poolFile, 'utf8')).map((s) => norm(s.replace(/^@[\w-]+:? /, ''))) : [];
const entries = []; const errors = [];
for (const f of fs.readdirSync(DIR).filter((n) => n.endsWith('.txt')).sort()) {
  const lines = fs.readFileSync(path.join(DIR, f), 'utf8').split('\n');
  for (let i = 0; i < lines.length; i++) {
    const m = /^>([eb]?) (.*)$/.exec(lines[i]); if (!m) continue;
    let j = i + 1; while (j < lines.length && (lines[j].startsWith('#') || !lines[j].trim())) j++;
    const kind = m[1] || 'j'; let src = norm(m[2]);
    const fields = (lines[j] || '').replace(/\s+$/, '').split(' ¦ ');
    const want = kind === 'b' ? 4 : 3;
    if (fields.length !== want) { errors.push(`${f}:${i + 1} expected ${want} fields, got ${fields.length}: ${src}`); continue; }
    if (src.endsWith('⋯')) {
      const p = src.slice(0, -1).trim(); const hits = [...new Set(pool.filter((s) => s.startsWith(p)))];
      if (hits.length !== 1) { errors.push(`${f}:${i + 1} prefix matches ${hits.length}: ${p}`); continue; }
      src = hits[0];
    }
    const t = {}; const order = kind === 'j' ? ['en', 'zh-CN', 'ko'] : kind === 'e' ? ['ja', 'zh-CN', 'ko'] : LOCS;
    order.forEach((loc, k) => { const v = fields[k].trim() === '_' ? null : fields[k].replace(/^\s+$/, ''); t[loc] = v; });
    if (kind === 'j') t.ja = null; if (kind === 'e') t.en = null;
    entries.push({ src, t, kind, where: `${f}:${i + 1}` });
  }
}
const dicts = Object.fromEntries(LOCS.map((l) => [l, { exact: new Map(), tpl: new Map(), alias: new Map() }]));
const put = (d, map, k, v, where) => { if (map.has(k) && map.get(k) !== v && map === d.exact) errors.push(`dup ${k} (${where})`); map.set(k, v); };
for (const e of entries) {
  const isT = /\{\d+\}/.test(e.src);
  for (const loc of LOCS) {
    const v = e.t[loc]; if (v == null) continue;
    put(dicts[loc], isT ? dicts[loc].tpl : dicts[loc].exact, e.src, v, e.where);
  }
  // Aliases: other renditions of the same message (e.g. a page's own English text shown in zh mode) map too.
  const renditions = { ja: e.kind === 'j' ? e.src : e.t.ja, en: e.kind === 'e' ? e.src : e.t.en };
  for (const loc of LOCS) {
    const target = e.t[loc] ?? (loc === 'ja' && e.kind === 'j' ? e.src : loc === 'en' && e.kind === 'e' ? e.src : null);
    if (target == null) continue;
    for (const r of Object.values(renditions)) {
      if (!r || r === e.src || norm(r) === norm(target) || norm(r).replace(/\{\d+\}/g, '').trim().length < 2) continue;
      const k = norm(r); const d = dicts[loc];
      if ((isT ? d.tpl : d.exact).has(k)) continue;
      d.alias.set(k, { v: target, isT });
    }
  }
}
for (const loc of LOCS) {
  const d = dicts[loc];
  for (const [k, { v, isT }] of d.alias) { const m = isT ? d.tpl : d.exact; if (!m.has(k)) m.set(k, v); }
  const exact = Object.fromEntries([...d.exact].map(([k, v]) => [norm(k), v]));
  const lit = (s) => s.replace(/\{\d+\}/g, '').length;
  const tpl = [...d.tpl].map(([k, v]) => [norm(k), v]).sort((a, b) => lit(b[0]) - lit(a[0]));
  const body = `// Generated by services/zeronyth-l1/i18n-pages/build.mjs; edit the .txt sources there.\nexport const EXACT = ${JSON.stringify(exact, null, 0)};\nexport const TEMPLATES = ${JSON.stringify(tpl)};\n`;
  fs.writeFileSync(path.join(OUT, `i18n-pages-${loc}.mjs`), body);
  d.out = { exact: new Map(Object.entries(exact)), tpl: tpl.map(([src, out]) => { const names = []; const re = new RegExp('^' + src.split(/(\{\d+\})/).map((p) => { const m = /^\{(\d+)\}$/.exec(p); if (m) { names.push(+m[1]); return '(.+?)'; } return p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }).join('') + '$', 's'); return { re, names, out }; }) };
  console.log(loc, 'exact', Object.keys(exact).length, 'templates', tpl.length);
}
function tr(d, text, depth = 0) { const k = norm(text); if (!k) return null; if (d.exact.has(k)) return d.exact.get(k); if (depth > 3) return null; for (const { re, names, out } of d.tpl) { const m = re.exec(k); if (m) return out.replace(/\{(\d+)\}/g, (_, n) => { const v = m[names.indexOf(+n) + 1] ?? ''; return tr(d, v, depth + 1) ?? v; }); } return null; }
if (errors.length) { console.log('ERRORS:\n' + errors.join('\n')); }
if (pool.length) {
  const JA = /[\u3040-\u30ff\u3400-\u9fff]/;
  const missing = pool.filter((s) => tr(dicts.en.out, s) == null && tr(dicts.ja.out, s) == null);
  fs.writeFileSync('/workspace/i18n-audit/missing.txt', missing.join('\n') + '\n');
  console.log('pool', pool.length, 'uncovered', missing.length);
  void JA;
}
